#!/usr/bin/env node
/* Regenerate the reference tables that are derived from scripts/versions.mjs.
 *
 *   node scripts/gen-docs.mjs            # write references/ftbquests-types.md
 *   node scripts/gen-docs.mjs --check    # exit 1 when the file is stale
 *
 * Keeping the tables generated means a new FTB Quests version only has to be
 * added to versions.mjs, never to the prose.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { FIELD_SINCE, FTBQ_VERSIONS, REWARD_FIELDS, TASK_FIELDS } from './versions.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const outFile = join(here, '..', 'references', 'ftbquests-types.md');
const VERSIONS = Object.keys(FTBQ_VERSIONS);
const LOADER_ONLY = {
  forge_energy: 'Forge/NeoForge only (Fabric packs do not register it)',
  tech_reborn_energy: 'Fabric TechReborn integration only - not listed below',
};

function cell(ok) {
  return ok ? 'yes' : '-';
}

function availability(kind) {
  return VERSIONS.map((v) => {
    const list = kind === 'task' ? FTBQ_VERSIONS[v].taskTypes : FTBQ_VERSIONS[v].rewardTypes;
    return `| \`${kind === 'task' ? '' : ''}\` |`;
  });
}

function fieldList(fields) {
  if (!fields || fields.length === 0) return 'none';
  return fields.map((f) => `\`${f}\``).join(', ');
}

function firstVersion(kind, id) {
  for (const v of VERSIONS) {
    const list = kind === 'task' ? FTBQ_VERSIONS[v].taskTypes : FTBQ_VERSIONS[v].rewardTypes;
    if (list.includes(id)) return v;
  }
  return 'unknown';
}

function table(kind, fields) {
  const ids = Object.keys(fields);
  const lines = [];
  lines.push(`| ${kind} | ${VERSIONS.join(' | ')} | required | optional |`);
  lines.push(`|---|${VERSIONS.map(() => '---').join('|')}|---|---|`);
  for (const id of ids) {
    const cols = VERSIONS.map((v) => {
      const list = kind === 'task' ? FTBQ_VERSIONS[v].taskTypes : FTBQ_VERSIONS[v].rewardTypes;
      return cell(list.includes(id));
    });
    const entry = fields[id] ?? {};
    lines.push(`| \`${id}\` | ${cols.join(' | ')} | ${fieldList(entry.required)} | ${fieldList(entry.optional)} |`);
  }
  return lines.join('\n');
}

function build() {
  const generated = [];
  generated.push('# FTB Quests task and reward types');
  generated.push('');
  generated.push('<!-- generated by scripts/gen-docs.mjs - edit versions.mjs, not this file -->');
  generated.push('');
  generated.push('A type the target version does not register is **not an error in game**: the loader replaces it with a');
  generated.push('Custom task/reward titled `Unknown type: <id>`, which never completes and is saved back as');
  generated.push('`type: "custom"`, losing the original spelling. Check the availability column before writing quest');
  generated.push('data for an old pack, or pass `--ftbq <ver>` to the validator and let `task-type-unknown` /');
  generated.push('`reward-type-unknown` catch it.');
  generated.push('');
  generated.push('Conversely, a task/reward **without** a `type` field is defaulted to `item` - for a task that means it');
  generated.push('completes on the first item pickup, which is why the validator reports it as an error.');
  generated.push('');
  generated.push('`id` and `type` are written by every task and reward compound; they are not repeated in the field columns.');
  generated.push('Required fields are the ones FTB Quests reads unconditionally; optional fields only appear when set.');
  generated.push('');
  generated.push('## Tasks');
  generated.push('');
  generated.push(table('task', TASK_FIELDS));
  generated.push('');
  for (const [id, note] of Object.entries(LOADER_ONLY)) {
    if (id in TASK_FIELDS) generated.push(`- \`${id}\`: ${note}`);
  }
  generated.push('');
  generated.push('## Rewards');
  generated.push('');
  generated.push(table('reward', REWARD_FIELDS));
  generated.push('');
  generated.push('## Fields that older versions drop');
  generated.push('');
  generated.push('These keys exist only from the listed version on. Writing them into an older pack is silently ignored,');
  generated.push('which is how a quest ends up "not behaving as written" after a downgrade or a copy from a newer pack.');
  generated.push('');
  generated.push('| key | since |');
  generated.push('|---|---|');
  for (const [key, since] of Object.entries(FIELD_SINCE)) {
    generated.push(`| \`${key}\` | ${since} |`);
  }
  generated.push('');
  generated.push('## Version notes');
  generated.push('');
  generated.push('| layout | Minecraft | text location | reward tables | notes |');
  generated.push('|---|---|---|---|---|');
  for (const v of VERSIONS) {
    const spec = FTBQ_VERSIONS[v];
    const text = spec.hasLangFiles ? '`lang/<locale>.snbt`' : 'inside the chapter file';
    const tables = spec.rewardTableDir ? `\`${spec.rewardTableDir}/\`` : 'inline `table_data` only';
    generated.push(`| \`${v}\` | ${spec.mcVersions.join(', ')} | ${text} | ${tables} | file version ${spec.fileVersion} |`);
  }
  generated.push('');
  const late = [];
  for (const [id] of Object.entries(TASK_FIELDS)) {
    const first = firstVersion('task', id);
    if (first !== VERSIONS[0]) late.push(`- task \`${id}\` appears first in ${first}`);
  }
  for (const [id] of Object.entries(REWARD_FIELDS)) {
    const first = firstVersion('reward', id);
    if (first !== VERSIONS[0]) late.push(`- reward \`${id}\` appears first in ${first}`);
  }
  generated.push('## Late arrivals');
  generated.push('');
  generated.push('Every other id exists in every listed version.');
  generated.push('');
  generated.push(late.join('\n'));
  generated.push('');
  return generated.join('\n');
}

const text = build();
const mode = process.argv.includes('--check') ? 'check' : 'write';
if (mode === 'check') {
  let existing = '';
  try {
    existing = readFileSync(outFile, 'utf8');
  } catch {
    existing = '';
  }
  if (existing !== text) {
    console.error(`${outFile} is stale; run node scripts/gen-docs.mjs`);
    process.exit(1);
  }
  console.log(`${outFile} is up to date`);
} else {
  writeFileSync(outFile, text, 'utf8');
  console.log(`wrote ${outFile} (${text.split('\n').length} lines)`);
}
